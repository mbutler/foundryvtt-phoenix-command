// LEG10206, the World War II Weapon Data Supplement: hand-transcribed page by page and
// checked against the page's own text layer. The data layout is LEG10200's.
//
// A row is written as printed. Ranges are the book's 10, 20, 40, 70, 100, 200, 300 and 400
// hexes; a row runs left to right from 10 hexes and stops where the page stops printing, so a
// short array is a weapon whose data ends early, never a gap. The printed ROF cell is kept
// verbatim (`*`, `N`, `*N`, `**N`, `-`). Ammunition is keyed by its printed type in lower case;
// the page stars some types (`*JHP`) and does not say why, so the star is recorded in
// `starred` and nothing reads it. Ballistic Accuracy and Time of Flight are not carried, as
// in the core catalogue.
export const leg10206Source = Object.freeze({ book: 'LEG10206', title: 'World War II Weapon Data Supplement' });

const w = (pdfPage, id, name, category, calibre, country, physical, aim, ammo, extra = {}) =>
  Object.freeze({ pdfPage, id, name, category, calibre, country, physical, aim, ammo, ...extra });
// Compact rows: numbers separated by spaces; "-" is a column the page leaves blank.
const n = text => text.trim().split(/\s+/).map(v => v === '-' ? null : Number(v));
// Aim as printed: action counts and modifiers in pairs ("1 -23 2 -12 ... 12 0").
const aim = text => { const v = n(text), out = {}; for (let i = 0; i < v.length; i += 2) out[String(v[i])] = v[i + 1]; return out; };
const ammo = (pen, dc, starred = false) => ({ ...(starred ? { starred: true } : {}), pen: n(pen), dc: n(dc) });
const phys = (L, W, RT, ROF, Cap, AW, feed, KD, SAB) => ({ L: String(L), W, RT, ROF: String(ROF), Cap, AW, feed, KD, SAB });

